func checkReference(c *catalog.Catalog) string {
	var b strings.Builder
	header(&b, c, "Check reference",
		"One entry per check: what it tests, which facts it reads, how to fix what "+
			"it finds, and what it maps to. This is `plumbline explain CHECK-ID` "+
			"for the whole catalog at once — the command is the same material and "+
			"needs no network, no bundle and no privileges.")

	for _, m := range modules(c) {
		fmt.Fprintf(&b, "## %s\n\n", m.name)
		for _, ck := range m.checks {
			entry(&b, ck)
		}
	}
	return b.String()
}

func entry(b *strings.Builder, ck catalog.Check) {
	fmt.Fprintf(b, "### %s — %s\n\n", ck.ID, escape(ck.Title))

	if ck.Deprecated != nil {
		fmt.Fprintf(b, "> **Deprecated since catalog %d.** %s\n",
			ck.Deprecated.SinceCatalog, escape(ck.Deprecated.Reason))
		if len(ck.Deprecated.ReplacedBy) > 0 {
			fmt.Fprintf(b, "> Replaced by %s.\n", code(ck.Deprecated.ReplacedBy))
		}
		b.WriteString(">\n> A retired ID is never reused and never renumbered: it is in\n" +
			"> suppression files and in bundles on disk.\n\n")
	}

	b.WriteString("| | |\n|---|---|\n")
	fmt.Fprintf(b, "| Module | `%s` |\n", ck.Module)
	fmt.Fprintf(b, "| Base severity | %s |\n", ck.BaseSeverity)
	fmt.Fprintf(b, "| Since | catalog %d |\n", ck.SinceCatalog)
	fmt.Fprintf(b, "| Reads | %s |\n", factList(ck))
	if len(ck.Tags) > 0 {
		fmt.Fprintf(b, "| Tags | %s |\n", code(ck.Tags))
	}
	b.WriteString("\n")

	if ck.Description != "" {
		b.WriteString(strings.TrimSpace(ck.Description) + "\n\n")
	}

	// The same sentence `plumbline explain` prints, and it is the load-bearing
	// one: a check that cannot see what it needs says UNKNOWN rather than
	// guessing, and a reader of this document has to know that before they read
	// a PASS as reassurance.
	b.WriteString("If a fact it reads was not collected — a file the scan could not read, " +
		"a collector that failed — this check reports `UNKNOWN` with a reason rather " +
		"than guessing.\n\n")

	if r := ck.Remediation; r != nil {
		fmt.Fprintf(b, "**Remediation** — effort %s\n\n", r.Effort)
		if r.Summary != "" {
			b.WriteString(escape(r.Summary) + "\n\n")
		}
		for i, step := range r.Steps {
			fmt.Fprintf(b, "%d. %s\n", i+1, escape(step))
		}
		if len(r.Steps) > 0 {
			b.WriteString("\n")
		}
		if len(r.Commands) > 0 {
			b.WriteString("```sh\n" + strings.Join(r.Commands, "\n") + "\n```\n\n")
		}
		if r.Caution != "" {
			b.WriteString("> **Caution.** " + escape(r.Caution) + "\n\n")
		}
	}

	if len(ck.Mappings) > 0 {
		var refs []string
		for _, m := range ck.Mappings {
			refs = append(refs, fmt.Sprintf("`%s %s`", m.Framework, m.Control))
		}
		fmt.Fprintf(b, "**Controls** — %s\n\n", strings.Join(refs, ", "))
	}
	if len(ck.References) > 0 {
		b.WriteString("**References**\n\n")
		for _, r := range ck.References {
			if r.URL != "" {
				fmt.Fprintf(b, "- [%s](%s)\n", escape(r.Title), r.URL)
			} else {
				fmt.Fprintf(b, "- %s\n", escape(r.Title))
			}
		}
		b.WriteString("\n")
	}
	b.WriteString("---\n\n")
}

