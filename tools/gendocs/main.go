func header(b *strings.Builder, c *catalog.Catalog, title, intro string) {
	b.WriteString(generatedBanner + "\n\n")
	fmt.Fprintf(b, "# %s\n\n", title)
	fmt.Fprintf(b, "**Catalog version %d · %d checks · %d modules**\n\n",
		version.Catalog(), c.Len(), len(modules(c)))
	b.WriteString(intro + "\n\n")

	// Stated in both documents rather than in one, because either may be the
	// page somebody lands on from a search engine.
	b.WriteString("Plumbline reports evidence, not compliance conclusions. " +
		"A control mapping names an identifier that a check is *relevant to*; " +
		"it is not a claim of compliance with it, and no control text is " +
		"reproduced here (see [COMPLIANCE-DATA-POLICY.md](COMPLIANCE-DATA-POLICY.md)).\n\n---\n\n")
}

type module struct {
	name   string
	checks []catalog.Check
}

// modules groups the catalog by module, both sorted, so the generated document
// is a pure function of the catalog and two runs produce identical bytes.
func modules(c *catalog.Catalog) []module {
	byName := map[string][]catalog.Check{}
	for _, id := range c.IDs() {
		ck, ok := c.Get(id)
		if !ok {
			continue
		}
		byName[ck.Module] = append(byName[ck.Module], ck)
	}

	names := sortedKeys(byName)
	out := make([]module, 0, len(names))
	for _, n := range names {
		checks := byName[n]
		sort.Slice(checks, func(i, j int) bool { return checks[i].ID < checks[j].ID })
		out = append(out, module{name: n, checks: checks})
	}
	return out
}

func severities(checks []catalog.Check) map[string]int {
	out := map[string]int{}
	for _, ck := range checks {
		out[strings.ToUpper(string(ck.BaseSeverity))]++
	}
	return out
}

func factList(ck catalog.Check) string {
	if len(ck.Requires) == 0 {
		return "—"
	}
	ids := make([]string, 0, len(ck.Requires))
	for _, id := range ck.Requires {
		ids = append(ids, string(id))
	}
	sort.Strings(ids)
	return code(ids)
}

func code(in []string) string {
	out := make([]string, 0, len(in))
	for _, s := range in {
		out = append(out, "`"+s+"`")
	}
	return strings.Join(out, ", ")
}

// anchor reproduces GitHub's heading-slug rule for "### ID — Title", so the
// links in MODULE-CATALOG.md land on the right entry.
func anchor(id, title string) string {
	slug := strings.ToLower(id + " — " + title)
	var b strings.Builder
	for _, r := range slug {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9', r == '-':
			b.WriteRune(r)
		case r == ' ':
			b.WriteRune('-')
		}
	}
	return b.String()
}

// escape neutralises the Markdown a check's own prose could otherwise inject
// into a table cell. Titles and remediation steps are written by check authors
// and contain pipes, underscores and asterisks — a path like
// /etc/pam.d/*.conf ends a table row early and italicises the rest of the file.
func escape(s string) string {
	r := strings.NewReplacer(
		`|`, `\|`,
		`*`, `\*`,
		`_`, `\_`,
		"\n", " ",
	)
	return strings.TrimSpace(r.Replace(s))
}

func sortedKeys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
