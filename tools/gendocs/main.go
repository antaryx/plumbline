func moduleCatalog(c *catalog.Catalog) string {
	var b strings.Builder
	header(&b, c, "Module catalog",
		"Every module this build carries, and how many checks each contributes. "+
			"The per-check detail is in [CHECK-REFERENCE.md](CHECK-REFERENCE.md).")

	mods := modules(c)

	b.WriteString("| Module | Checks | Critical | High | Medium | Low | Info |\n")
	b.WriteString("|---|---:|---:|---:|---:|---:|---:|\n")
	var total int
	totals := map[string]int{}
	for _, m := range mods {
		sev := severities(m.checks)
		fmt.Fprintf(&b, "| `%s` | %d | %d | %d | %d | %d | %d |\n",
			m.name, len(m.checks),
			sev["CRITICAL"], sev["HIGH"], sev["MEDIUM"], sev["LOW"], sev["INFO"])
		total += len(m.checks)
		for k, v := range sev {
			totals[k] += v
		}
	}
	fmt.Fprintf(&b, "| **total** | **%d** | %d | %d | %d | %d | %d |\n\n",
		total, totals["CRITICAL"], totals["HIGH"], totals["MEDIUM"], totals["LOW"], totals["INFO"])

	b.WriteString("Severity is the check's **base** severity, before any context " +
		"adjustment a finding may carry.\n\n---\n\n")

	for _, m := range mods {
		fmt.Fprintf(&b, "## %s\n\n", m.name)
		b.WriteString("| Check | Severity | Reads |\n|---|---|---|\n")
		for _, ck := range m.checks {
			fmt.Fprintf(&b, "| [`%s`](CHECK-REFERENCE.md#%s) %s | %s | %s |\n",
				ck.ID, anchor(ck.ID, ck.Title), escape(ck.Title),
				ck.BaseSeverity, factList(ck))
		}
		b.WriteString("\n")
	}
	return b.String()
}

