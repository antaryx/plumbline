// Command gendocs writes docs/MODULE-CATALOG.md and docs/CHECK-REFERENCE.md
// from the catalog this binary carries.
//
// docs/DOCUMENT-MAP.md marks both as *generated* and says they are never
// hand-maintained, and the reason is the one that makes generated reference
// documentation worth having at all: a hand-written list of 79 checks is a list
// that is wrong within a month, and wrong reference documentation for a
// security tool is worse than none, because somebody will act on it.
//
// The catalog comes from cli.Catalog(), which is the same assembly the binary
// evaluates with. There is no second list of checks: a document generated from
// a copy would describe a catalog nobody runs.
//
// Two modes, mirroring tools/fixturegate:
//
//	go run ./tools/gendocs           write the files
//	go run ./tools/gendocs -check    exit 1 if they are out of date
//
// The second is wired into `make invariants`, so a check added without
// regenerating is a failed build rather than a discovery six months later.
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/antaryx/plumbline/internal/catalog"
	"github.com/antaryx/plumbline/internal/cli"
	"github.com/antaryx/plumbline/internal/version"
)

const docsDir = "docs"

// generatedBanner heads both files. It is not decoration: without it the first
// person to find a typo fixes it in the output, the fix survives exactly until
// the next regeneration, and they conclude the generator ate their work.
const generatedBanner = `<!-- Generated by tools/gendocs. Do not edit.
     Run ` + "`make docs`" + ` after changing the catalog. -->`

func main() {
	check := flag.Bool("check", false, "verify the committed files are current instead of writing them")
	flag.Parse()

	c := cli.Catalog()
	files := map[string]string{
		"MODULE-CATALOG.md":  moduleCatalog(c),
		"CHECK-REFERENCE.md": checkReference(c),
	}

	if *check {
		if err := verify(files); err != nil {
			fmt.Fprintf(os.Stderr, "gendocs: %v\n", err)
			os.Exit(1)
		}
		fmt.Printf("ok: generated docs current (%d checks, catalog %d)\n", c.Len(), version.Catalog())
		return
	}

	for name, body := range files {
		path := filepath.Join(docsDir, name)
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil { //nolint:gosec // a documentation file
			fmt.Fprintf(os.Stderr, "gendocs: writing %s: %v\n", path, err)
			os.Exit(1)
		}
		fmt.Printf("wrote %s\n", path)
	}
}

func verify(files map[string]string) error {
	for _, name := range sortedKeys(files) {
		path := filepath.Join(docsDir, name)
		got, err := os.ReadFile(path) //nolint:gosec // a documentation file
		if err != nil {
			return fmt.Errorf("%s is missing; run `make docs`", path)
		}
		if string(got) != files[name] {
			return fmt.Errorf("%s is out of date; run `make docs` and commit the result", path)
		}
	}
	return nil
}

